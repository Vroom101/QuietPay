// Generates src/abi/PaymentRouter.ts from the Foundry build. Never hand-write the ABI.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../../contracts/out/PaymentRouter.sol/PaymentRouter.json");
const out = resolve(here, "../src/abi/PaymentRouter.ts");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/gen-abi.mjs from the Foundry build. Do not edit by hand.\nexport const paymentRouterAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log("wrote", out);
